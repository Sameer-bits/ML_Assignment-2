@st.cache_data
def load_comparison_results():
    """
    Read the model comparison table generated by train_models.py.

    The column-name handling below accepts common alternatives such
    as 'F1', 'F1_score', and 'F1 Score'.
    """
    if not COMPARISON_FILE.exists():
        return None, (
            f"Comparison file not found: {COMPARISON_FILE}. "
            "Run train_models.py to generate it."
        )

    try:
        results = pd.read_csv(COMPARISON_FILE)

        normalised = {
            str(column).strip().lower().replace("_", " ").replace("-", " "): column
            for column in results.columns
        }

        required_aliases = {
            "Model": ["model", "algorithm", "classifier"],
            "Accuracy": ["accuracy"],
            "AUC": ["auc", "roc auc", "roc auc score"],
            "Precision": ["precision"],
            "Recall": ["recall"],
            "F1 Score": ["f1 score", "f1", "f1 measure"],
            "MCC": ["mcc", "matthews correlation coefficient"],
        }

        rename_columns = {}
        for standard_name, aliases in required_aliases.items():
            for alias in aliases:
                if alias in normalised:
                    rename_columns[normalised[alias]] = standard_name
                    break

        results = results.rename(columns=rename_columns)

        missing_columns = [
            column
            for column in ["Model"] + ["Accuracy", "AUC", "Precision", "Recall", "F1 Score", "MCC"]
            if column not in results.columns
        ]

        if missing_columns:
            return None, (
                "The comparison CSV is missing these required columns: "
                + ", ".join(missing_columns)
            )

        results = results[["Model"] + ["Accuracy", "AUC", "Precision", "Recall", "F1 Score", "MCC"]].copy()
        results["Model"] = results["Model"].astype(str).str.strip()

        # Convert metric columns to numeric values.
        for column in ["Accuracy", "AUC", "Precision", "Recall", "F1 Score", "MCC"]:
            results[column] = pd.to_numeric(
                results[column],
                errors="coerce",
            )

        if results.empty or results["Model"].isna().any():
            return None, "The comparison CSV does not contain valid model rows."

        return results, None

    except (OSError, pd.errors.ParserError, UnicodeDecodeError) as error:
        return None, f"Could not read model_comparison.csv: {error}"


comparison_results, error = load_comparison_results()   
if error:
    st.error(error)



